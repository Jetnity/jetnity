function codes(anzahl: number): string[] {
  const liste: string[] = [...FLUGHAFEN_BEISPIELE]
  for (let i = 0; liste.length < anzahl; i += 1) {
    const code = `Q${String.fromCharCode(65 + (i % 26))}${String.fromCharCode(65 + Math.floor(i / 26))}`
    if (!liste.includes(code)) liste.push(code)
  }
  return liste
}

function flughaefen(anzahl: number): FlughafenImportZeile[] {
  return codes(anzahl).map((iata, i) => ({
    iata,
    icao: `X${iata}`,
    name: `${iata} Airport`,
    city: iata === 'ZRH' ? 'Zurich' : null,
    region: iata === 'ZRH' ? 'Zurich' : null,
    country: iata === 'ZRH' ? 'Switzerland' : 'Testland',
    countryCode: iata === 'ZRH' ? 'CH' : 'TL',
    lat: iata === 'ZRH' ? 47.4647 : (i % 80) + 0.25,
    lon: iata === 'ZRH' ? 8.5492 : -((i % 170) + 0.5),
    keywords: iata === 'ZRH' ? 'Zürich Kloten' : null,
    klasse: 'large',
  }))
}

