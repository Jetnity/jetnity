#!/usr/bin/env node
// Local synthetic interaction evidence on the EXISTING account harness.
// Start this checkout's own Next server on 3497; no fixture activation on Vercel.
import assert from 'node:assert/strict'
import { mkdirSync, writeFileSync } from 'node:fs'
import { chromium } from 'playwright'

const base = 'http://127.0.0.1:3497'
const output = 'docs/evidence/account-world-explorer-1'
mkdirSync(output, { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const report = { environment: 'local existing /ui-audit/account; synthetic fixtures; Chromium desktop/touch emulation, not real devices', checks: [], errors: [] }
const widths = [360, 390, 768, 1280, 1440]
const check = (name, detail) => { report.checks.push({ name, detail }); console.log(name) }
const world = '/ui-audit/account?zustand=welt&ansicht=besuche'
const searchName = 'Länder und Orte in deinem Konto suchen'
const goto = (page, path = world) => page.goto(base + path, { waitUntil: 'networkidle' })
const wait = (page) => page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))))
async function geometry(page) {
  return page.locator('[data-explorer-viewport]').evaluate((element) => {
    const rect = element.getBoundingClientRect()
    const s = Number(element.dataset.scale), x = Number(element.dataset.panX), y = Number(element.dataset.panY)
    const matrix = element.querySelector('[data-explorer-transform]').getScreenCTM()
    const probe = new DOMPoint(180, 77).matrixTransform(matrix)
    const expected = { x: rect.left + (0.5 * s + x) * rect.width, y: rect.top + (0.5 * s + y) * rect.height }
    const markers = [...element.querySelectorAll('[data-explorer-marker]')].map((m) => {
      const r = m.getBoundingClientRect()
      return { width: r.width, height: r.height, x: r.left + r.width / 2, y: r.top + r.height / 2, expectedX: rect.left + parseFloat(m.style.left) / 100 * rect.width, expectedY: rect.top + parseFloat(m.style.top) / 100 * rect.height }
    })
    return { s, x, y, error: Math.max(Math.abs(probe.x - expected.x), Math.abs(probe.y - expected.y)), markers }
  })
}
function assertGeometry(g) {
  assert.ok(g.error < 1, `SVG viewport drift ${g.error}`)
  assert.ok(g.x <= 0 && g.x >= 1 - g.s && g.y <= 0 && g.y >= 1 - g.s)
  for (const marker of g.markers) {
    assert.ok(marker.width >= 44 && marker.height >= 44)
    assert.ok(Math.abs(marker.x - marker.expectedX) < 1 && Math.abs(marker.y - marker.expectedY) < 1)
  }
}
try {
  for (const width of widths) {
    const page = await browser.newPage({ viewport: { width, height: 900 }, hasTouch: width < 768, reducedMotion: 'reduce' })
    const errors = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.route('**/*', (route) => {
      const req = route.request()
      if (req.method() !== 'GET' || !req.url().startsWith(base)) return route.abort()
      return route.continue()
    })
    await goto(page)
    const search = page.getByRole('searchbox', { name: searchName })
    await search.fill('portugál')
    await wait(page)
    assert.equal(await page.locator('[data-explorer-result^="land:"]').count(), 1)
    const country = page.locator('[data-explorer-result="land:PT"]')
    await country.focus()
    await page.keyboard.press('Enter')
    await wait(page)
    const details = page.locator('[data-explorer-details]')
    assert.equal(await details.locator('[data-explorer-visit]').count(), 2)
    assert.equal(await details.getByRole('link').count(), 2)
    assert.match(await details.innerText(), /2019[\s\S]*14. Juli 2012/)
    assert.match(await details.innerText(), /Besucht und geplant/)
    assert.equal(await details.locator('h3').evaluate((el) => document.activeElement === el), true)
    const links = await details.getByRole('link').evaluateAll((els) => els.map((el) => el.getAttribute('href')))
    assert.deepEqual(links, ['/reisen/11111111-1111-4111-8111-111111111111', '/reisen/33333333-3333-4333-8333-333333333333'])
    const totals = await page.locator('[data-explorer-totals]').innerText()
    for (const filter of ['Besucht', 'Geplant', 'Beides']) {
      await page.getByRole('button', { name: filter, exact: true }).click()
      assert.match(await country.innerText(), /Besucht und geplant/)
      assert.equal(await page.locator('[data-explorer-totals]').innerText(), totals)
      assert.equal(await page.locator('[data-welt-land="PT"]').first().getAttribute('data-welt-land-zustand'), 'beides')
    }
    await page.getByRole('button', { name: 'Alle', exact: true }).click()
    await search.fill('Atlantis')
    assert.equal(await page.locator('[data-explorer-details]').count(), 0)
    assert.match(await page.locator('[data-explorer-results]').innerText(), /Keine passenden Einträge/)
    assert.equal(await page.locator('[data-welt-land]').count(), 0)
    await page.getByRole('button', { name: 'Suche leeren' }).click()
    assert.equal(await search.inputValue(), '')
    assert.ok(await page.locator('[data-explorer-result]').count() > 5)
    await search.fill('sao')
    assert.match(await page.locator('[data-explorer-results]').innerText(), /São Paulo/)
    await search.fill('Osaka')
    assert.match(await page.locator('[data-explorer-results]').innerText(), /Keine nutzbare Kartenposition/)
    await search.fill('Auckland')
    await page.locator('[data-explorer-result^="ort:"]').click()
    assert.match(await details.innerText(), /Kein gespeicherter Ländercode/)
    await page.getByRole('button', { name: 'Details schliessen' }).click()
    assert.equal(await page.locator('[data-explorer-result^="ort:"]').evaluate((el) => document.activeElement === el), true)
    await page.getByRole('button', { name: 'Suche leeren' }).click()
    const viewport = page.locator('[data-explorer-viewport]')
    await viewport.focus()
    for (let i = 0; i < 8; i++) await page.keyboard.press('+')
    assert.equal(await viewport.getAttribute('data-scale'), '4')
    await page.keyboard.press('ArrowRight')
    await page.keyboard.press('ArrowDown')
    await wait(page)
    assertGeometry(await geometry(page))
    await page.setViewportSize({ width: width + 17, height: 850 })
    await wait(page)
    assertGeometry(await geometry(page))
    await page.setViewportSize({ width, height: 900 })
    await page.getByRole('button', { name: 'Zurücksetzen', exact: true }).click()
    assert.equal(await viewport.getAttribute('data-scale'), '1')
    assert.equal(await viewport.getAttribute('data-pan-x'), '0')
    assert.equal(await viewport.getAttribute('data-pan-y'), '0')
    assert.equal(await viewport.evaluate((el) => getComputedStyle(el).touchAction), 'pan-y pinch-zoom')
    await search.focus()
    await page.keyboard.type('+-')
    assert.equal(await viewport.getAttribute('data-scale'), '1')
    await page.getByRole('button', { name: 'Suche leeren' }).click()
    assert.equal(await search.getAttribute('maxlength'), '120')
    await page.getByRole('button', { name: 'Karte vergrössern' }).click()
    await page.getByRole('button', { name: 'Karte verschieben', exact: true }).click()
    await viewport.scrollIntoViewIfNeeded()
    const box = await viewport.boundingBox()
    await page.mouse.move(box.x + box.width * 0.5, box.y + box.height * 0.5)
    await page.mouse.down()
    await page.mouse.move(box.x + box.width * 0.65, box.y + box.height * 0.6, { steps: 10 })
    await page.mouse.up()
    await wait(page)
    assert.notEqual(await viewport.getAttribute('data-pan-x'), '-0.25')
    assert.equal(await page.locator('[data-explorer-details]').count(), 0)
    assertGeometry(await geometry(page))
    await viewport.dispatchEvent('pointercancel', { pointerId: 1, isPrimary: true })
    const afterCancel = await viewport.getAttribute('data-pan-x')
    await page.mouse.move(box.x + 10, box.y + 10)
    assert.equal(await viewport.getAttribute('data-pan-x'), afterCancel)
    await page.getByRole('button', { name: 'Kartenbewegung beenden' }).click()
    await page.getByRole('button', { name: 'Zurücksetzen', exact: true }).click()
    const group = page.locator('[data-explorer-marker]').filter({ hasText: /^[2-9]\d*$/ }).first()
    await group.click()
    assert.equal(await page.getByText('Mehrere Einträge an dieser Stelle', { exact: true }).count(), 1)
    await page.getByRole('button', { name: 'Ortsauswahl schliessen' }).click()
    await search.fill('Portugal')
    await country.click()
    await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
    await wait(page)
    if (width === 390 || width === 1440) await page.screenshot({ path: `${output}/after-${width}.png`, fullPage: true })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), true)
    assert.deepEqual(errors, [])
    check(`viewport-${width}`, 'search/diacritics/counts, repeated visits/partial dates, distinct trip IDs, all filters/both-state/totals, no-match/clear, no-country/no-coordinate, focus/close, keyboard scope, 1–4x/reset, SVG+HTML alignment, resize, drag/cancel, groups, 44px targets, no overflow/page errors')
    await page.close()
  }
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true })
  await goto(page)
  const cdp = await page.context().newCDPSession(page)
  const surface = page.locator('[data-explorer-viewport]')
  await surface.scrollIntoViewIfNeeded()
  const box = await surface.boundingBox()
  const startScroll = await page.evaluate(() => scrollY)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: box.x + box.width / 2, y: box.y + box.height / 2 }] })
  for (let i = 1; i <= 6; i++) await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: box.x + box.width / 2, y: box.y + box.height / 2 - i * 15 }] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await page.waitForTimeout(300)
  assert.notEqual(await page.evaluate(() => scrollY), startScroll)
  check('touch-scroll', 'Chromium touch dispatch over map scrolls page in default mode')
  await page.getByRole('button', { name: 'Karte vergrössern' }).tap()
  await page.getByRole('button', { name: 'Karte verschieben', exact: true }).tap()
  await surface.scrollIntoViewIfNeeded()
  const b = await surface.boundingBox()
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: b.x + b.width / 2, y: b.y + b.height / 2 }] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: b.x + b.width / 2 + 30, y: b.y + b.height / 2 }] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  assert.notEqual(await surface.getAttribute('data-pan-x'), '-0.25')
  await page.getByRole('button', { name: 'Kartenbewegung beenden' }).tap()
  check('touch-map-pan', 'Explicit movement mode pans; mode can be ended by touch')
  for (const state of ['besuch-fehler', 'fehler', 'leer']) {
    await goto(page, `/ui-audit/account?zustand=${state}&ansicht=besuche`)
    await page.getByRole('button', { name: 'Beides', exact: true }).tap()
    const text = await page.locator('[data-world-map]').innerText()
    assert.match(text, state === 'leer' ? /Keine passenden Einträge|Noch keine Länder/ : /unbekannt|nicht bestimmbar/)
    assert.equal(await page.locator('[data-explorer-result]').count(), 0)
    check(state, 'Empty/intersection state is honest; independent load-error text retained')
  }
  await goto(page, '/ui-audit/account?dichte=40')
  const results = page.locator('[data-explorer-result]')
  assert.equal(await results.count(), 24)
  await page.getByRole('button', { name: /Weitere Einträge zeigen/ }).tap()
  assert.equal(await results.count(), 47)
  check('progressive-disclosure', '24 of 47 initially, all 47 reachable, total never truncated')
  await goto(page, '/ui-audit/account?zustand=welt')
  assert.equal(await page.locator('[data-world-map-darstellung="uebersicht"]').count(), 1)
  assert.equal(await page.getByRole('searchbox', { name: searchName }).count(), 0)
  assert.ok(await page.locator('[data-world-map-marker]').count() > 0)
  await page.locator('[data-world-map-marker]').first().tap()
  assert.equal(await page.getByRole('link', { name: 'Deine Welt öffnen', exact: true }).getAttribute('href'), '/account/welt')
  check('compact-overview', 'Existing markers and world link remain, full explorer controls absent')
  await goto(page)
  await page.getByRole('searchbox', { name: searchName }).fill('Portugal')
  await page.locator('[data-explorer-result="land:PT"]').tap()
  await page.locator('[data-explorer-details] a').first().tap()
  await page.waitForURL('**/reisen/11111111-1111-4111-8111-111111111111')
  check('trip-link-navigation', 'Click reaches exact stored fixture-ID /reisen path in existing application; authenticated trip content not verified')
  await goto(page, '/account/welt')
  assert.ok(page.url().includes('/login?next='))
  check('actual-account-page', 'Unauthenticated /account/welt redirects to login; no authenticated account session used')
  await page.close()
} catch (error) {
  report.errors.push(String(error.stack))
  throw error
} finally {
  await browser.close()
  writeFileSync(`${output}/interactions.json`, JSON.stringify(report, null, 2).replaceAll(process.cwd(), '<checkout>'))
  console.log(JSON.stringify({ checks: report.checks.length, failures: report.errors.length }))
}
