 const s=file('at-dev-temporary-sequence-restart.ROLLBACK.sql')
 assert.match(s,/CREATE TEMP SEQUENCE pg_temp\.at_recovery_seq/)
 assert.match(s,/ALTER SEQUENCE pg_temp\.at_recovery_seq RESTART WITH/)
