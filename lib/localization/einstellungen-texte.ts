export const EINSTELLUNGEN_TEXTE: Readonly<Record<UiSprache, Readonly<Record<EinstellungenTextSchluessel, string>>>> = { de, en }
export const EINSTELLUNGEN_SCHLUESSEL = Object.keys(de) as EinstellungenTextSchluessel[]

export function einstellungenText(sprache: UiSprache, schluessel: EinstellungenTextSchluessel): string {
  return EINSTELLUNGEN_TEXTE[sprache][schluessel]
}

const LOESCH_FEHLER: Record<KontoloeschungFehlerCode, EinstellungenTextSchluessel> = {
  bestaetigung: 'delete.error.bestaetigung', sitzung: 'delete.error.sitzung', passwort: 'delete.error.passwort',
  rate: 'delete.error.rate', mfa_code: 'delete.error.mfa_code', mfa_erforderlich: 'delete.error.mfa_erforderlich',
  oauth: 'delete.error.oauth', veraltet: 'delete.error.veraltet', nicht_gefunden: 'delete.error.nicht_gefunden',
  aufraeumen: 'delete.error.aufraeumen', teilweise: 'delete.error.teilweise', umgebung: 'delete.error.umgebung',
  netz: 'delete.error.netz', unbekannt: 'delete.error.unbekannt',
}
const LOESCH_PHASE: Record<KontoloeschungPhase, EinstellungenTextSchluessel> = {
  bereit: 'delete.phase.bereit', arbeiten: 'delete.phase.arbeiten', mfa: 'delete.phase.mfa',
  fertig: 'delete.phase.fertig', fehler: 'delete.phase.fehler', nicht_unterstuetzt: 'delete.error.oauth',
}

/** Presentation only. No password, confirmation, MFA or deletion logic. */
export function lokalisierterLoeschstatus(sprache: UiSprache, phase: KontoloeschungPhase, fehler: KontoloeschungFehlerCode | null): string {
  return einstellungenText(sprache, fehler ? LOESCH_FEHLER[fehler] ?? 'delete.error.unbekannt' : LOESCH_PHASE[phase] ?? 'delete.error.unbekannt')
}
