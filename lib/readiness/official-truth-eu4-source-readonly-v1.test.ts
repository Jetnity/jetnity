import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {test} from 'node:test'
const sql=readFileSync(new URL('../../scripts/db/official-truth-universal-registry-dev-1/eu4-200-visa-national-primary-readonly-v1.sql',import.meta.url),'utf8')
test('EU4 200-passport source evidence uses an exact PostgreSQL17 read-only snapshot and checks national primary portal links',()=>{
 assert.match(sql,/BEGIN TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY;/)
 assert.ok(sql.trimEnd().endsWith('ROLLBACK;'))
 for(const domain of ['vistoperitalia.esteri.it','france-visas.gouv.fr','interior.gob.es','www.gov.pt',
  'home-affairs.ec.europa.eu','eur-lex.europa.eu'])assert.ok(sql.includes(domain))
 assert.match(sql,/registered_official_urls @> ARRAY\[p\.required_official_primary\]::text\[\]/)
 assert.match(sql,/source_snapshot_class='RESEARCH_ONLY_UNVERIFIED_CONTENT'/)
 assert.match(sql,/\(200,4,80,76,40,4\)/)
 assert.match(sql,/\(5200,0\)/)
 assert.match(sql,/es_financial_conflict_cases=30/)
 assert.match(sql,/other_financial_conflicts=0/)
 assert.match(sql,/official_v3_guard_private\.assert_catalog_v1\(\)/)
 assert.match(sql,/public\.official_v3_guard_alarm_status_v1\(\)->>'status'/)
 assert.match(sql,/NATIONAL_OFFICIAL_PORTAL_LINKED_EU_VISA_BASELINE_PROPOSAL_NOT_APPROVED/)
 assert.match(sql,/SOURCE_LINK_OR_QUARANTINE_GUARD_REFUSED/)
})
test('EU4 200 candidates do not port Austria bilateral waivers, publish unsupported visa or expand Spanish money conflict to other topics',()=>{
 assert.match(sql,/WHEN b\.bmi_group='H' THEN 'F'/)
 assert.match(sql,/WHEN e\.citizenship_code=e\.destination_code THEN 'H'/)
 assert.match(sql,/c\.destination_code='FR' AS distinguish_france_overseas_territory_before_rule/)
 assert.match(sql,/c\.destination_code='ES' AS check_specific_es_financial_means_before_rule/)
 assert.match(sql,/f\.topic='financial_means' AND f\.unresolved_original_conflict/)
 assert.match(sql,/do_not_port_austrian_national_passport_exceptions/)
 assert.match(sql,/false AS destination_passport_original_digest_sealed/)
 assert.match(sql,/false AS destination_visa_legal_rule_qualified/)
 assert.match(sql,/false AS ma1_owner_aal2_approved/)
 assert.match(sql,/false AS publication_allowed/)
 assert.match(sql,/false AS applicant_document_residence_purpose_and_route_verified/)
 assert.match(sql,/NULL::numeric AS legal_fee/)
 assert.match(sql,/'derzeit nicht verfügbar'::text AS personal_visa_decision/)
 assert.match(sql,/'derzeit nicht verfügbar'::text AS entry_vaccination/)
 assert.doesNotMatch(sql,/\b(?:CREATE|ALTER|INSERT|UPDATE|DELETE|DROP|TRUNCATE|GRANT|REVOKE)\b\s+(?:TABLE|VIEW|FUNCTION|ROLE|POLICY|INTO|FROM)/i)
})
