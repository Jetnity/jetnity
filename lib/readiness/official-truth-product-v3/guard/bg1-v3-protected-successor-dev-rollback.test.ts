import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {test} from 'node:test'
const sql=readFileSync(new URL('../../../../scripts/db/official-truth-bg1-self-heal-dev-1/rehearse-protected-successor-v3.ROLLBACK.sql',import.meta.url),'utf8')

test('BG1 V3 real Dev rehearsal is a single rolled-back transaction with exact predecessor and private RLS',()=>{
 assert.ok(sql.startsWith('-- DEV-ONLY TRANSACTIONAL REHEARSAL'))
 assert.match(sql,/^BEGIN;$/m)
 assert.ok(sql.trimEnd().endsWith('ROLLBACK;'))
 assert.match(sql,/PERFORM official_v3_guard_private\.assert_catalog_v1\(\)/)
 assert.match(sql,/pg_try_advisory_xact_lock\(771106,1\)/)
 assert.match(sql,/CREATE TABLE official_v3_guard_private\.bg1_transient_baseline_v3/)
 assert.match(sql,/predecessor_catalog_digest text NOT NULL/)
 assert.match(sql,/predecessor_baseline_digest text NOT NULL/)
 assert.match(sql,/ALTER TABLE official_v3_guard_private\.bg1_transient_baseline_v3 FORCE ROW LEVEL SECURITY/)
 assert.match(sql,/CREATE POLICY postgres_only/)
 assert.match(sql,/CREATE TRIGGER immutable_rows BEFORE UPDATE OR DELETE/)
 assert.match(sql,/CREATE TRIGGER immutable_truncate BEFORE TRUNCATE/)
 assert.match(sql,/REVOKE ALL ON official_v3_guard_private\.bg1_transient_baseline_v3/)
 assert.doesNotMatch(sql,/GRANT .*\b(?:anon|authenticated|service_role)\b|ALTER ROLE/)
})
test('BG1 v3 protects same complete predecessor history and new catalog, never silently auto-accepts platform role drift',()=>{
 assert.match(sql,/CREATE OR REPLACE FUNCTION official_v3_guard_private\.audit_v1\(\)/)
 assert.match(sql,/CREATE OR REPLACE FUNCTION official_v3_guard_private\.latch_incident_v1\(/)
 assert.match(sql,/CREATE OR REPLACE FUNCTION official_v3_guard_private\.assert_catalog_v1\(\)/)
 assert.match(sql,/CREATE OR REPLACE FUNCTION official_v3_guard_private\.require_open_v1\(\)/)
 assert.match(sql,/CREATE OR REPLACE FUNCTION public\.official_v3_guard_alarm_status_v1\(\)/)
 assert.match(sql,/bg1_v3\.predecessor_catalog_digest/)
 assert.match(sql,/bg1_v3\.predecessor_baseline_digest/)
 assert.match(sql,/bg1_v3\.catalog IS DISTINCT FROM official_v3_guard_private\.catalog_status_v1\(\)/)
 assert.match(sql,/renewal\.predecessor_baseline_digest/)
 assert.match(sql,/renewal\.predecessor_catalog_digest/)
 assert.match(sql,/official_v3_at_private\.whole_originals_v2/)
 assert.match(sql,/required_generation<=renewal\.required_generation/)
 assert.match(sql,/v\.proof_not_before,earliest_proof/)
})
test('Immediately after install the public read returns unavailable until a NEW real full BG1 audit; Owner cannot be skipped',()=>{
 assert.match(sql,/SELECT greatest\(v\.required_generation,required_proof\)/)
 assert.match(sql,/INTO STRICT required_proof,earliest_proof/)
 assert.match(sql,/s\.generation<required_proof/)
 assert.match(sql,/current_state\.generation<required_proof/)
 assert.match(sql,/public\.official_v3_guard_alarm_status_v1\(\)->>'status'<>'unavailable'/)
 assert.match(sql,/v\.proof_not_before>s\.last_proof_started/)
 assert.match(sql,/DEV_BG1_V3_NATIVE_INTEGRATION_PG17_ROLLBACK_PASS/)
 assert.doesNotMatch(sql,/INSERT INTO official_v3_method_private\.heads_v1|UPDATE official_v3_guard_private\.state_v1 SET resumed_generation/)
})
