import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {test} from 'node:test'
const source=readFileSync(new URL('../../../../scripts/db/official-truth-bg1-self-heal-dev-1/production-bg1-v3-chain-exact.CANDIDATE-ROLLBACK.sql',import.meta.url),'utf8')
const executable=source.split('\n').filter(row=>!row.trimStart().startsWith('--')).join('\n')
test('Production BG1 candidate remains rollback-only and refuses unexplained role or code drift',()=>{
 assert.ok(source.startsWith('-- Production-specific BG1 v3 immutable successor CANDIDATE. Do not install.'))
 assert.ok(executable.trimEnd().endsWith('ROLLBACK;'))
 assert.doesNotMatch(executable,/^\s*COMMIT\s*;/im)
 assert.doesNotMatch(executable,/\bALTER\s+ROLE\b/i)
 assert.match(executable,/BG1_PROD_V3_UNKNOWN_CATALOG_DRIFT/)
 assert.match(executable,/BG1_PROD_V3_PRELOAD_SCOPE_CHANGED/)
 assert.match(executable,/session_preload_libraries=safeupdate/)
 assert.match(executable,/session_preload_libraries=supautils, safeupdate/)
 assert.match(executable,/pg_get_functiondef\(to_regprocedure\(v\.signature\)\)/)
 assert.match(executable,/pg_try_advisory_xact_lock\(771106,1\)/)
})
test('Production successor maintains its actual chain instead of the different Dev history',()=>{
 assert.match(executable,/official_v3_guard_private\.at_batch_switch_baseline_v2/)
 assert.doesNotMatch(executable,/source_renewal_baseline_v1/)
 for(const name of ['saved_offers_baseline_v1','weather_quota_baseline_v1','at_source_monitor_baseline_v1','rolling_quota_baseline_v1','admin_runtime_baseline_v1'])
   assert.ok(executable.includes(name),name)
 for(const name of ['audit_v1','latch_incident_v1','assert_catalog_v1','require_open_v1','catalog_status_v1','official_v3_guard_alarm_status_v1','jetnity_bg1_alarm_kind_v2'])
   assert.ok(executable.includes(name),name)
 assert.match(executable,/bg1_v3\.predecessor_catalog_digest/)
 assert.match(executable,/bg1_v3\.predecessor_baseline_digest/)
 assert.match(executable,/bg1_v3\.catalog IS DISTINCT FROM official_v3_guard_private\.catalog_status_v1\(\)/)
 assert.match(executable,/required_generation<=switch_v2\.required_generation/)
 assert.match(executable,/bg1_transient_baseline_v3 FORCE ROW LEVEL SECURITY/)
 assert.match(executable,/TRIGGER immutable_truncate BEFORE TRUNCATE/)
 assert.match(executable,/BG1_PROD_V3_POSTCHECK_STOP/)
})
test('Production v3 preview must remain visitor-unavailable until a future full audit, never issuing visas or resuming Owner',()=>{
 assert.match(executable,/v\.required_generation/)
 assert.match(executable,/v\.proof_not_before/)
 assert.match(executable,/public\.official_v3_guard_alarm_status_v1\(\)->>'status' IS DISTINCT FROM 'unavailable'/)
 assert.match(executable,/has_function_privilege\('anon','public\.jetnity_bg1_alarm_kind_v2\(\)','EXECUTE'\)/)
 assert.doesNotMatch(executable,/\b(?:INSERT|UPDATE)\s+(?:INTO\s+)?official_v3_method_private\.heads_v1|UPDATE\s+official_v3_guard_private\.state_v1\s+SET\s+resumed_generation/i)
})
