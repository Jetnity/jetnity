import assert from 'node:assert/strict'
import {test} from 'node:test'
import {readFileSync} from 'node:fs'
const base=new URL('../../../../',import.meta.url)
const file=(p:string)=>readFileSync(new URL(p,base),'utf8')
const sql=file('scripts/db/official-truth-bg1-self-heal-dev-1/rehearse-protected-successor-v3-with-five-minute-alarm.ROLLBACK.sql')
const dto=file('scripts/db/official-truth-bg1-self-heal-dev-1/bg1-five-minute-alarm-kind-v2.CANDIDATE.sql')
const workflow=file('.github/workflows/official-truth-bg1-five-minute-integrity-alarm.yml')
test('Protected BG1-v3 Dev rehearsal captures the public integrity-only DTO inside the immutable successor',()=>{
 assert.ok(sql.startsWith('-- DEV-ONLY TRANSACTIONAL REHEARSAL'))
 assert.ok(sql.trimEnd().endsWith('ROLLBACK;'))
 assert.match(sql,/CREATE TABLE official_v3_guard_private\.bg1_transient_baseline_v3/)
 assert.match(sql,/CREATE OR REPLACE FUNCTION official_v3_guard_private\.catalog_status_v1\(\)/)
 assert.match(sql,/'jetnity_bg1_alarm_kind_v2'/)
 assert.match(sql,/CREATE FUNCTION public\.jetnity_bg1_alarm_kind_v2\(\)/)
 assert.match(sql,/CREATE OR REPLACE FUNCTION official_v3_guard_private\.assert_catalog_v1\(\)/)
 assert.match(sql,/bg1_v3\.catalog IS DISTINCT FROM official_v3_guard_private\.catalog_status_v1\(\)/)
 assert.match(sql,/alarmCatalogProtected/)
 assert.match(sql,/anonReadOnly/)
 assert.match(sql,/DEV_BG1_V3_NATIVE_INTEGRATION_PG17_ROLLBACK_PASS/)
 assert.doesNotMatch(sql,/ALTER ROLE|UPDATE official_v3_guard_private\.state_v1 SET resumed_generation|GRANT .*SERVICE_ROLE/i)
})
test('BG1 notifier RPC returns only coarse status/incident generation, cannot expose raw role or perform owner recovery',()=>{
 assert.match(dto,/CREATE FUNCTION public\.jetnity_bg1_alarm_kind_v2\(\) RETURNS jsonb/)
 assert.match(dto,/SECURITY DEFINER SET search_path=pg_catalog/)
 assert.match(dto,/reason IN \('refused','clock'\)/)
 assert.match(dto,/generation>s\.resumed_generation/)
 assert.match(dto,/integrity_locked/)
 assert.match(dto,/temporarily_unavailable/)
 assert.match(dto,/schema',1/)
 assert.match(dto,/EXCEPTION WHEN OTHERS THEN/)
 assert.match(dto,/GRANT EXECUTE ON FUNCTION public\.jetnity_bg1_alarm_kind_v2\(\) TO anon/)
 assert.doesNotMatch(dto,/UPDATE |DELETE |INSERT |TRUNCATE |ALTER ROLE|owner_aal2|source_body|password/i)
})
test('Paused alarm workflow preserves manual dispatch, public-only key and exact Production Owner arm',()=>{
 assert.match(workflow,/^  workflow_dispatch:/m)
 assert.doesNotMatch(workflow,/^  schedule:/m)
 assert.doesNotMatch(workflow,/^\s*-?\s*cron:/m)
 assert.match(workflow,/github.repository == 'Jetnity\/jetnity'/)
 assert.match(workflow,/github.ref == 'refs\/heads\/main'/)
 assert.match(workflow,/vars\.JETNITY_BG1_FIVE_MIN_ALARM == 'production:qscbgcdmivbbnzrcyegn:integrity-only-v2'/)
 assert.match(workflow,/github.event.repository.private == false/)
 assert.match(workflow,/issues: write/)
 assert.match(workflow,/JETNITY_PROD_SUPABASE_PUBLISHABLE_KEY/)
 assert.match(workflow,/GITHUB_TOKEN: \$\{\{ github.token \}\}/)
 assert.doesNotMatch(workflow,/SUPABASE_SERVICE_ROLE_KEY|SUPABASE_DB_PASSWORD|GH_PAT|NEXT_PUBLIC_SUPABASE_SERVICE/i)
})
