import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { test } from 'node:test'
const sql=readFileSync(new URL(
 '../../scripts/db/official-truth-universal-registry-dev-1/install.sql',import.meta.url),'utf8')

test('one private registry imports existing AT, 6-country, 4-country and USAGov sources',()=>{
 assert.match(sql,/CREATE SCHEMA jetnity_source_registry_private AUTHORIZATION postgres/)
 assert.match(sql,/official_v3_at_source_watch_private\.pins_v1/)
 assert.match(sql,/jetnity_global_source_monitor_private\.sources_v1/)
 assert.match(sql,/jetnity_followup_source_monitor_private\.sources_v3/)
 assert.match(sql,/jetnity_usagov_fallback_private\.original_v1/)
 assert.match(sql,/REGISTERED_SOURCE_SEED_MISMATCH/)
 assert.match(sql,/sources_v1\)<>19/)
 assert.match(sql,/passport_scope_v1\)<>950/)
 assert.match(sql,/topic_scope_v1\)<>21/)
 assert.match(sql,/DISTINCT destination_code\) FROM jetnity_source_registry_private\.sources_v1\)<>11/)
})
test('all passport and topic links remain unqualified possible research impact only',()=>{
 assert.match(sql,/POTENTIAL_RESEARCH_IMPACT/)
 assert.match(sql,/REVIEW_TOPIC_CANDIDATE/)
 assert.match(sql,/CHECK\(NOT passport_rule_qualified\)/)
 assert.match(sql,/CHECK\(NOT topic_fact_approved\)/)
 assert.match(sql,/CHECK\(NOT source_custody_verified\)/)
 assert.match(sql,/CHECK\(NOT legal_rule_qualified\)/)
 assert.match(sql,/CHECK\(NOT publication_allowed\)/)
 assert.match(sql,/CHECK\(accepted_facts=0\)/)
 assert.match(sql,/CROSS JOIN jetnity_global_research_private\.passport_priority_v1/)
 assert.match(sql,/WHEN 'AT' THEN 1 WHEN 'IT' THEN 2 WHEN 'FR' THEN 3/)
 assert.match(sql,/WHEN 'ES' THEN 4 WHEN 'PT' THEN 5/)
})
test('new countries are registered by one shared API, not bespoke monitoring code',()=>{
 assert.match(sql,/CREATE FUNCTION jetnity_source_registry_private\.register_research_source_v1\(/)
 assert.match(sql,/p_destination_code text,p_source_key text,p_official_url text,/)
 assert.match(sql,/p_topics text\[\],p_interval_minutes integer/)
 assert.match(sql,/session_user<>'postgres' OR current_user<>session_user/)
 assert.match(sql,/p_interval_minutes NOT BETWEEN 30 AND 43200/)
 assert.match(sql,/cardinality\(p_topics\) NOT BETWEEN 1 AND 12/)
 assert.match(sql,/p_official_url!~'\^https:\/\//)
 assert.match(sql,/monitor_family,migration_state,/)
 assert.match(sql,/'GENERIC','REGISTERED_RESEARCH_ONLY'/)
 assert.match(sql,/SELECT sid,citizenship_code FROM jetnity_global_research_private\.passport_priority_v1/)
 assert.match(sql,/FROM unnest\(p_topics\) AS x\(topic\)/)
 assert.match(sql,/SOURCE_REGISTRY_UNQUALIFIED_INTAKE_REJECTED/)
})
test('the unified status is a research-only reader and protected AT monitoring remains separate',()=>{
 assert.match(sql,/CREATE VIEW jetnity_source_registry_private\.latest_research_status_v1/)
 assert.match(sql,/WITH \(security_invoker=true\)/)
 assert.match(sql,/FROM jetnity_global_source_monitor_private\.observations_v1 o/)
 assert.match(sql,/FROM jetnity_followup_source_monitor_private\.observations_v3 o/)
 assert.match(sql,/FROM jetnity_usagov_watch_private\.observations_v1 o/)
 assert.match(sql,/LEGACY_AT_PROTECTED_MONITOR_UNTOUCHED/)
 assert.match(sql,/REGISTERED_AWAITING_AUTHORITY_CHECK/)
 assert.doesNotMatch(sql,/FROM official_v3_at_source_watch_private\.reads_v1/)
 assert.match(sql,/false::boolean AS publication_allowed/)
 assert.match(sql,/0::integer AS accepted_facts/)
})
test('no new HTTP, cron job, method, role or production grant and one transaction',()=>{
 assert.match(sql,/^-- DEV ONLY/)
 assert.match(sql,/dev:yfvbxvijcorffwxbxahl:UNIVERSAL-REGISTRY-V1/)
 assert.equal((sql.match(/^BEGIN;$/gm)??[]).length,1)
 assert.equal((sql.match(/^COMMIT;$/gm)??[]).length,1)
 assert.match(sql,/official_v3_guard_private\.assert_catalog_v1\(\)/)
 assert.doesNotMatch(sql,/\bnet\.http_get\s*\(|\bnet\.http_post\s*\(|\bcron\.schedule\s*\(|\bcron\.alter_job\s*\(/)
 assert.doesNotMatch(sql,/\bALTER ROLE\b|\bCREATE ROLE\b|\bCREATE OR REPLACE FUNCTION\s+public\.|\bGRANT (SELECT|EXECUTE)\b|qscbgcdmivbbnzrcyegn/)
})
test('private registry has strict RLS, deny-all readers and append-only constraints',()=>{
 assert.equal((sql.match(/ENABLE ROW LEVEL SECURITY;/g)??[]).length,3)
 assert.equal((sql.match(/FORCE ROW LEVEL SECURITY;/g)??[]).length,3)
 assert.equal((sql.match(/immutable_rows BEFORE UPDATE OR DELETE/g)??[]).length,3)
 assert.equal((sql.match(/immutable_truncate BEFORE TRUNCATE/g)??[]).length,3)
 assert.match(sql,/REVOKE ALL ON ALL TABLES IN SCHEMA jetnity_source_registry_private/)
 assert.match(sql,/REVOKE ALL ON ALL FUNCTIONS IN SCHEMA jetnity_source_registry_private/)
 assert.match(sql,/REVOKE ALL ON SCHEMA jetnity_source_registry_private/)
 assert.match(sql,/UNIVERSAL_REGISTRY_DEV_POSTCHECK_ROLLBACK/)
})
