import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { test } from 'node:test'
const sql=readFileSync(new URL(
  '../../scripts/db/official-truth-usagov-fallback-dev-v1/install.sql',import.meta.url),'utf8')

test('USAGov alternative is pinned to exact private Dev response, not a new HTTP request',()=>{
 assert.match(sql,/^-- DEV ONLY\./)
 assert.match(sql,/dev:yfvbxvijcorffwxbxahl:USAGOV-FALLBACK-V1/)
 assert.match(sql,/session_user<>'postgres' OR current_user<>session_user/)
 assert.match(sql,/current_database\(\)<>'postgres'/)
 assert.match(sql,/server_version_num/)
 assert.match(sql,/net\._http_response n WHERE n\.id=558/)
 assert.match(sql,/status_code=200/)
 assert.match(sql,/content_type~\*'\^text\/html/)
 assert.match(sql,/octet_length\(convert_to\(n\.content,'UTF8'\)\)=42833/)
 assert.match(sql,/40f0bd8cf60b63b169218f790bcbb1c92d377ba96a11fdff639dbee72cb4de47/)
 assert.match(sql,/https:\/\/www\.usa\.gov\/visa-waiver-esta/)
 assert.equal((sql.match(/^BEGIN;$/gm)??[]).length,1)
 assert.equal((sql.match(/^COMMIT;$/gm)??[]).length,1)
 assert.doesNotMatch(sql,/\bnet\.http_get\s*\(|\bnet\.http_post\s*\(|\bcron\.schedule\s*\(|\bcron\.alter_job\s*\(/)
 assert.doesNotMatch(sql,/qscbgcdmivbbnzrcyegn|OPENAI_API_KEY|XAI_API_KEY|CREATE ROLE|ALTER ROLE/)
})
test('one government page is research ONLY, not a passport decision',()=>{
 assert.match(sql,/OPERATOR_INITIATED_ONEOFF_PG_NET_RESEARCH/)
 assert.match(sql,/CHECK\(NOT source_custody_verified\)/)
 assert.match(sql,/CHECK\(NOT legal_rule_qualified\)/)
 assert.match(sql,/CHECK\(accepted_fact_count=0\)/)
 assert.match(sql,/CHECK\(NOT publication_allowed\)/)
 assert.match(sql,/CHECK\(customer_answer='derzeit nicht verfügbar'\)/)
 assert.match(sql,/SELECT c\.destination_code,c\.citizenship_code,c\.priority_rank,/)
 assert.match(sql,/UNQUALIFIED_SOURCE_CANDIDATE/)
 assert.match(sql,/false::boolean AS legal_rule_qualified/)
 assert.match(sql,/false::boolean AS publication_allowed/)
 assert.match(sql,/0::integer AS accepted_fact_count/)
 assert.match(sql,/c\.destination_code='US'/)
 assert.match(sql,/original_v1\)<>1/)
 assert.match(sql,/us_passport_review_v1\)<>50/)
 assert.match(sql,/legal_rule_qualified OR publication_allowed OR accepted_fact_count<>0/)
 assert.doesNotMatch(sql,/\bUPDATE\s+jetnity_global_research_private\.|\bINSERT INTO\s+official_v3_/)
})
test('source body private, SHA-bound, append-only and never accessible to anon/authenticated',()=>{
 assert.match(sql,/CREATE SCHEMA jetnity_usagov_fallback_private AUTHORIZATION postgres/)
 assert.match(sql,/CHECK\(source_bytes=octet_length\(original_html\)\)/)
 assert.match(sql,/CHECK\(source_sha256=encode\(sha256\(original_html\),'hex'\)\)/)
 assert.match(sql,/ENABLE ROW LEVEL SECURITY/)
 assert.match(sql,/FORCE ROW LEVEL SECURITY/)
 assert.match(sql,/CREATE POLICY postgres_only/)
 assert.match(sql,/immutable_rows BEFORE UPDATE OR DELETE/)
 assert.match(sql,/immutable_truncate BEFORE TRUNCATE/)
 assert.match(sql,/WITH \(security_invoker=true\)/)
 assert.match(sql,/REVOKE ALL ON ALL TABLES IN SCHEMA/)
 assert.match(sql,/REVOKE ALL ON ALL FUNCTIONS IN SCHEMA/)
 assert.match(sql,/REVOKE ALL ON SCHEMA/)
 assert.match(sql,/official_v3_guard_private\.assert_catalog_v1\(\)/)
})
