import assert from 'node:assert/strict'
import { test } from 'node:test'
import { readFileSync } from 'node:fs'

const sql=readFileSync(
 new URL('../../../scripts/db/official-truth-global-research-dev-1/source-review-queue-v1.sql',import.meta.url),'utf8'
)
test('one private source-review pipeline for the canonical 206x50 matrix, no public visa conclusion',()=>{
 assert.match(sql,/GLOBAL-REVIEW-QUEUE-V1/)
 assert.match(sql,/jetnity_global_research_private\.destinations_v1\)<>206/)
 assert.match(sql,/jetnity_global_research_private\.passport_priority_v1\)<>50/)
 assert.match(sql,/jetnity_global_research_private\.cases_v1\)<>10300/)
 assert.match(sql,/CREATE VIEW jetnity_global_review_private\.passport_triage_v1/)
 assert.match(sql,/COUNT|count\(\*\)/i)
 assert.match(sql,/source_triage/)
 assert.match(sql,/NOT_YET_IN_GLOBAL_SOURCE_REGISTRY/)
 assert.match(sql,/BYTES_CHANGED_REQUIRES_LEGAL_REVIEW/)
 assert.match(sql,/SOURCE_COLLECTION_TIMEOUT/)
 assert.match(sql,/RESEARCH_ONLY_NOT_LEGALLY_QUALIFIED/)
 assert.match(sql,/false::boolean AS customer_rule_approved/)
 assert.match(sql,/false::boolean AS publication_allowed/)
 assert.doesNotMatch(sql,/CREATE (?:OR REPLACE )?FUNCTION public\.|GRANT\s+EXECUTE.*\b(?:anon|authenticated|service_role)\b|CREATE ROLE|ALTER ROLE/i)
})
test('all source evidence is append-only and source digest alone NEVER authorizes a legal rule',()=>{
 assert.match(sql,/CREATE TABLE jetnity_global_review_private\.events_v1/)
 assert.match(sql,/PRIMARY KEY\(batch_id,dest,source_key\)/)
 assert.match(sql,/REFERENCES jetnity_global_source_monitor_private\.observations_v1/)
 assert.match(sql,/RESEARCH_BYTES_CHANGED/)
 assert.match(sql,/SOURCE_UNAVAILABLE/)
 assert.match(sql,/SOURCE_BODY_REJECTED/)
 assert.match(sql,/original_result='same_unqualified_snapshot'/)
 assert.match(sql,/NOT source_qualified/)
 assert.match(sql,/NOT legal_fact_approved/)
 assert.match(sql,/NOT public_publish_allowed/)
 assert.match(sql,/ENABLE ROW LEVEL SECURITY/)
 assert.match(sql,/FORCE ROW LEVEL SECURITY/)
 assert.match(sql,/CREATE POLICY postgres_only/)
 assert.match(sql,/immutable_rows BEFORE UPDATE OR DELETE/)
 assert.match(sql,/immutable_truncate BEFORE TRUNCATE/)
 assert.match(sql,/REVOKE ALL ON SCHEMA jetnity_global_review_private/)
 assert.match(sql,/REVOKE ALL ON ALL TABLES IN SCHEMA jetnity_global_review_private/)
 assert.doesNotMatch(sql,/UPDATE\s+official_v3_|DELETE FROM official_v3_|INSERT INTO official_v3_source_renewal_private/i)
})
test('source data ingestion is scheduled, idempotent, bounded by existing BG1 and pilot source scope',()=>{
 assert.match(sql,/CREATE FUNCTION jetnity_global_review_private\.capture_v1\(\)/)
 assert.match(sql,/session_user<>'postgres'/)
 assert.match(sql,/current_user<>session_user/)
 assert.match(sql,/official_v3_guard_alarm_status_v1\(\)->>'status'<>'current'/)
 assert.match(sql,/pg_try_advisory_xact_lock\(771115,707\)/)
 assert.match(sql,/ON CONFLICT DO NOTHING/)
 assert.match(sql,/SELECT jetnity_global_review_private\.capture_v1\(\)/)
 assert.match(sql,/jetnity-global-source-review-queue-dev/)
 assert.match(sql,/\*\/5 \* \* \* \*/)
 assert.match(sql,/COUNT\(\*\)|count\(\*\)/)
 assert.match(sql,/PERFORM official_v3_guard_private\.assert_catalog_v1\(\)/)
 assert.match(sql,/BEGIN;/)
 assert.match(sql,/COMMIT;\s*$/)
})
test('a newly queued government fetch never invents an unchanged receipt',()=>{
 assert.match(sql,/LEFT JOIN LATERAL\(/)
 assert.match(sql,/evt\.batch_id=b\.batch_id/)
 assert.match(sql,/COLLECTION_PENDING/)
 assert.match(sql,/SOURCE_COLLECTION_TIMEOUT/)
 assert.match(sql,/b\.requested_at<=clock_timestamp\(\)-interval '6 minutes'/)
 assert.doesNotMatch(sql,/COALESCE\(.*publication_allowed.*,\s*true\)/i)
})
