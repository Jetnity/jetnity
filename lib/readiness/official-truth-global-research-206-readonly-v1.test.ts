import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {test} from 'node:test'
const sql=readFileSync(new URL('../../scripts/db/official-truth-universal-registry-dev-1/all-206-by-50-research-queue-readonly-v1.sql',import.meta.url),'utf8')
test('206 destinations x exact 50 passport-priority.csv rank are fully checked in one read-only database snapshot',()=>{
 assert.match(sql,/BEGIN TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY;/)
 assert.ok(sql.trimEnd().endsWith('ROLLBACK;'))
 assert.match(sql,/4515324024236916142857bf16d67590a7a1ca11c31fd1263e8b7979fd6eb358/)
 assert.match(sql,/official_v3_source_renewal_private\.passport_priority_v1/)
 assert.match(sql,/p\.rank=r\.priority_rank/)
 assert.match(sql,/r\.citizenship_code<>p\.code/)
 assert.match(sql,/r\.original_slice_path<>/)
 assert.match(sql,/source_snapshot_class<>'RESEARCH_ONLY_UNVERIFIED_CONTENT'/)
 assert.match(sql,/r\.customer_status<>'derzeit nicht verfügbar'/)
 assert.match(sql,/t\.destinations=206 AND t\.rows=10300/)
 assert.match(sql,/t\.ordinary_destinations=204/)
 assert.match(sql,/t\.special_regions=2/)
 assert.match(sql,/t\.fully_ranked=206/)
 assert.match(sql,/t\.rank_mismatches=0/)
 assert.match(sql,/t\.invalid_archive_path=0/)
 assert.match(sql,/t\.status_failures=0/)
 assert.match(sql,/current_database\(\)='postgres'/)
 assert.match(sql,/public\.official_v3_guard_alarm_status_v1\(\)->>'status'='current'/)
 assert.match(sql,/\(WHERE destination_code IN\('CN-HK','CN-MO'\)\)/)
})
