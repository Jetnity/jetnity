import assert from 'node:assert/strict'
import { test } from 'node:test'
import { readFileSync } from 'node:fs'
const sql=readFileSync(new URL('../../../scripts/db/official-truth-next-six-research-dev-1/install.sql',import.meta.url),'utf8')
test('all six next original 50-passport research queues are pinned and non-publishable',()=>{
 assert.match(sql,/NEXT6-1/)
 assert.match(sql,/original_50_slices_sha/)
 assert.match(sql,/CROSS JOIN official_v3_source_renewal_private.passport_priority_v1/)
 assert.match(sql,/<>300/)
 assert.match(sql,/<>11/)
 for(const code of ['GR','GB','US','TR','TH','AE'])assert.match(sql,new RegExp("'"+code+"'"))
 assert.match(sql,/('HR'|'NL')/)
 assert.match(sql,/AMBIGUOUS_UNSPLIT_V2_2_INDEX/)
 assert.match(sql,/status text NOT NULL DEFAULT 'derzeit nicht verfügbar'/)
 assert.match(sql,/accepted integer NOT NULL DEFAULT 0 CHECK\(accepted=0\)/)
 assert.match(sql,/published boolean NOT NULL DEFAULT false CHECK\(published=false\)/)
 assert.match(sql,/source_body_sha text CHECK\(source_body_sha IS NULL\)/)
 assert.match(sql,/verified boolean NOT NULL DEFAULT false CHECK\(verified=false\)/)
 assert.match(sql,/PERFORM official_v3_guard_private\.assert_catalog_v1\(\)/)
})
test('Thai updated official visa source and direct free TDAC form are candidates, not approved traveler duties',()=>{
 assert.match(sql,/2026-09-03/)
 assert.match(sql,/15 September 2026/)
 assert.match(sql,/https:\/\/tdac\.immigration\.go\.th\/arrival-card\//)
 assert.match(sql,/Thailand Digital Arrival Card/)
 assert.match(sql,/Fake-Seiten/)
 assert.match(sql,/form_cost=0/)
 assert.match(sql,/accepted boolean NOT NULL DEFAULT false/)
})
test('Dev-only migration protects research history and does not install customer-visible facts',()=>{
 assert.match(sql,/^-- DEV only/)
 assert.match(sql,/BEGIN;/)
 assert.match(sql,/COMMIT;\s*$/)
 assert.match(sql,/FORCE ROW LEVEL SECURITY/)
 assert.match(sql,/no_row_change BEFORE UPDATE OR DELETE/)
 assert.match(sql,/no_truncate BEFORE TRUNCATE/)
 assert.match(sql,/REVOKE ALL ON ALL TABLES IN SCHEMA jetnity_next_six_research_private/)
 assert.doesNotMatch(sql,/CREATE OR REPLACE FUNCTION public\.|GRANT EXECUTE|cron\.schedule/i)
 assert.doesNotMatch(sql,/REFERENCES official_v3_guard_private|REFERENCES official_v3_source_renewal_private/i)
})
