import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {test} from 'node:test'

const sql=readFileSync(new URL('../../../scripts/db/official-truth-universal-registry-dev-1/at-49-current-legal-scope-v3.sql',import.meta.url),'utf8')

test('AT 49 conditional visa source readback requires an exact fresh pair of audited BMI pages and unchanged seal',()=>{
 assert.match(sql,/BEGIN TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY;/)
 assert.ok(sql.trimEnd().endsWith('ROLLBACK;'))
 assert.match(sql,/r\.state='unchanged_exact'/)
 assert.match(sql,/r\.observed_sha=p\.raw_sha/)
 assert.match(sql,/r\.observed_bytes=p\.expected_bytes/)
 assert.match(sql,/r\.observed_at>=now\(\)-interval '70 minutes'/)
 assert.match(sql,/s\.source_batch_id=w\.batch_id/)
 assert.match(sql,/s\.outcome='unchanged'/)
 assert.match(sql,/current_setting\('server_version_num'\)::int\/10000=17/)
 assert.match(sql,/official_v3_guard_private\.assert_catalog_v1\(\)/)
 assert.match(sql,/public\.official_v3_guard_alarm_status_v1\(\)->>'status'/)
 assert.match(sql,/pinned_original_digest='fcec70ebb5e7869591eaa8490025288534f5e44dddc0926102cd0bb27de8e778'/)
 assert.match(sql,/bmi_source_version='2026-11-06'/)
 assert.match(sql,/\(50,20,19,10,1\)/)
 assert.match(sql,/\(3,5,9\)/)
 assert.match(sql,/OFFICIAL_SOURCE_STALE_OR_PROTECTED_CATALOG_REFUSED/)
})
test('AT 49 readback refuses individual visa, fee and vaccine approval and cannot touch protected catalog',()=>{
 assert.match(sql,/VISA_DUTY_ORDINARY_PASSPORT_BASELINE_EXCEPTIONS_PENDING/)
 assert.match(sql,/FREE_MOVEMENT_VALID_EU_EEA_CH_DOCUMENT_REQUIRED/)
 assert.match(sql,/SHORT_STAY_EXEMPT_ONLY_IF_PASSPORT_AND_90_180_RULES_MATCH/)
 assert.match(sql,/AUSTRIAN_HOME_NATIONAL_NOT_FOREIGN_VISA_CASE/)
 assert.match(sql,/bmi_exact_eu_exception/)
 assert.match(sql,/bmi_exact_national_exception/)
 assert.match(sql,/biometric_caveat/)
 assert.match(sql,/british_category_caveat/)
 assert.match(sql,/bilateral_caveat/)
 assert.match(sql,/separate_airport_transit_visa_review/)
 assert.match(sql,/false AS personal_legal_rule_qualified/)
 assert.match(sql,/false AS ma1_owner_aal2_approved/)
 assert.match(sql,/false AS publication_allowed/)
 assert.match(sql,/false AS individual_document_verified/)
 assert.match(sql,/false AS route_purpose_duration_verified/)
 for(const topic of ['individual_visum_result','entry_required_vaccination','entry_recommended_vaccination'])
  assert.ok(sql.includes("'derzeit nicht verfügbar'::text AS "+topic))
 assert.match(sql,/NULL::date AS legal_valid_until_unproven/)
 assert.doesNotMatch(sql,/\b(?:CREATE VIEW|CREATE TABLE|GRANT SELECT|GRANT EXECUTE|DROP TABLE|UPDATE|INSERT INTO|DELETE FROM|ALTER FUNCTION|CREATE ROLE|cron\.schedule)\b/i)
})
