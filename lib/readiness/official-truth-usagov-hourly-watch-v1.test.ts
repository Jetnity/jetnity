// USAGov private, hard-capped Dev source watch. Static first gate; a
// real PG17 transactional rehearsal and a natural cron readback are separate.
import assert from 'node:assert/strict'
import { test } from 'node:test'
import { readFileSync } from 'node:fs'
const sql=readFileSync(new URL(
 '../../scripts/db/official-truth-usagov-fallback-dev-v1/hourly-watch-v1.sql',import.meta.url),'utf8')

test('exact Dev-only and existing source predecessor; no new project, role, keys or publish path',()=>{
 assert.match(sql,/^-- DEV ONLY/)
 assert.match(sql,/dev:yfvbxvijcorffwxbxahl:USAGOV-HOURLY-V1/)
 assert.match(sql,/session_user<>'postgres' OR current_user<>session_user/)
 assert.match(sql,/current_database\(\)<>'postgres'/)
 assert.match(sql,/server_version_num/)
 assert.match(sql,/official_v3_guard_alarm_status_v1\(\)->>'status'<>'current'/)
 assert.match(sql,/source_sha256=encode\(sha256\(original_html\),'hex'\)/)
 assert.match(sql,/USAGOV_WATCH_DEV_EXACT_PREDECESSOR_REQUIRED/)
 assert.match(sql,/official_v3_guard_private\.assert_catalog_v1\(\)/)
 assert.equal((sql.match(/^BEGIN;$/gm)??[]).length,1)
 assert.equal((sql.match(/^COMMIT;$/gm)??[]).length,1)
 assert.doesNotMatch(sql,/qscbgcdmivbbnzrcyegn|OPENAI_API_KEY|XAI_API_KEY|\bCREATE ROLE\b|\bALTER ROLE\b|\bCREATE OR REPLACE\b/)
})
test('source request is fixed and spaced >=65 minutes, 320 total, hard storage stops',()=>{
 assert.equal((sql.match(/request_id:=net\.http_get\(/g)??[]).length,1)
 assert.match(sql,/request_id:=net\.http_get\('https:\/\/www\.usa\.gov\/visa-waiver-esta'/)
 assert.match(sql,/AND last_sent>clock_timestamp\(\)-interval '65 minutes'/)
 assert.match(sql,/IF n>=320/)
 assert.match(sql,/25165824/)
 assert.match(sql,/pg_database_size\(current_database\(\)\)>=268435456/)
 assert.match(sql,/request_id bigint PRIMARY KEY/)
 assert.match(sql,/http_get\('https:\/\/www\.usa\.gov\/visa-waiver-esta',\s*'\{\}'::jsonb,'\{"accept":"text\/html"\}'::jsonb,15000\)/)
 assert.doesNotMatch(sql,/\bnet\.http_post\s*\(|\bcron\.schedule\s*\(|\bnet\.http_delete\s*\(/i)
})
test('all source results are append-only and remain legally unqualified',()=>{
 assert.match(sql,/CREATE TABLE jetnity_usagov_watch_private\.observations_v1/)
 assert.match(sql,/CREATE TABLE jetnity_usagov_watch_private\.requests_v1/)
 assert.match(sql,/CHECK\(NOT source_custody_verified\)/)
 assert.match(sql,/CHECK\(NOT legal_rule_qualified\)/)
 assert.match(sql,/CHECK\(NOT publication_allowed\)/)
 assert.match(sql,/CHECK\(accepted_fact_count=0\)/)
 assert.match(sql,/CHECK\(customer_answer='derzeit nicht verfügbar'\)/)
 assert.match(sql,/body_bytes=octet_length\(source_body\)/)
 assert.match(sql,/raw_sha=encode\(sha256\(source_body\),'hex'\)/)
 assert.match(sql,/FORCE ROW LEVEL SECURITY/g)
 assert.match(sql,/CREATE POLICY postgres_only/g)
 assert.match(sql,/immutable_rows BEFORE UPDATE OR DELETE/g)
 assert.match(sql,/immutable_truncate BEFORE TRUNCATE/g)
 assert.match(sql,/REVOKE ALL ON ALL TABLES IN SCHEMA jetnity_usagov_watch_private/)
 assert.match(sql,/REVOKE ALL ON ALL FUNCTIONS IN SCHEMA jetnity_usagov_watch_private/)
 assert.match(sql,/REVOKE ALL ON SCHEMA jetnity_usagov_watch_private/)
 assert.doesNotMatch(sql,/\bUPDATE\s+jetnity_global_research_private\b|INSERT INTO official_v3_|CREATE POLICY .*TO anon/i)
})
test('HTTP 403, empty/failed response, stale pending and changed bytes fail closed',()=>{
 assert.match(sql,/collection_timeout/)
 assert.match(sql,/source_unavailable/)
 assert.match(sql,/invalid_source_body/)
 assert.match(sql,/changed_requires_review/)
 assert.match(sql,/unchanged_unqualified/)
 assert.match(sql,/item\.status_code IS DISTINCT FROM 200/)
 assert.match(sql,/item\.requested_at>clock_timestamp\(\)-interval '8 minutes'/)
 assert.match(sql,/octet_length\(convert_to\(item\.content,'UTF8'\)\) NOT BETWEEN 1000 AND 131072/)
 assert.match(sql,/position\('captcha' IN lower\(left\(item\.content,4096\)\)\)>0/)
 assert.match(sql,/earlier_hash=new_hash/)
 assert.match(sql,/ON CONFLICT DO NOTHING/)
 assert.match(sql,/SELECT jetnity_usagov_watch_private\.tick_v1\(\)/)
})
test('single existing cron collector is extended, not replaced or duplicated',()=>{
 assert.match(sql,/prior:=jetnity_source_body_private\.capture_all_v2\(\)/)
 assert.match(sql,/collected:=jetnity_usagov_watch_private\.collect_v1\(\)/)
 assert.match(sql,/queued:=jetnity_usagov_watch_private\.enqueue_v1\(\)/)
 assert.match(sql,/cron\.alter_job\(job_id,/)
 assert.match(sql,/command=>'SELECT jetnity_usagov_watch_private\.tick_v1\(\)'/)
 assert.match(sql,/USAGOV_WATCH_POSTCHECK_ROLLBACK/)
 assert.doesNotMatch(sql,/\bcron\.schedule\s*\(/)
})
