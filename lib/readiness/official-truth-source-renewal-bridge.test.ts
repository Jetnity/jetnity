import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {test} from 'node:test'
const sql=readFileSync(new URL('../../scripts/db/official-truth-source-bound-renewal-dev-1/install.sql',import.meta.url),'utf8')
